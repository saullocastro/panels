"""Write the kernels ``calc_kTv`` into ``panels/models/<model>_num.pyx``

The kernel of each model of ``tangent_product.MODELS`` is generated from the
expressions of ``tangent_product.py`` and written between the markers
``BEGIN`` and ``END`` at the end of each ``_num.pyx``, replacing a previous
version::

    python write_pyx.py [model ...]

The generators of whole modules, ``fsdt_tsdt/write_pyx.py`` and
``cylshell_clpt_sanders/write_pyx.py``, append the same block through
:func:`pyx_block`.

"""
import os
import re
import sys

from sympy import Float, Rational, Symbol, collect
from sympy.printing.str import StrPrinter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, REPO)

import tangent_product as th
from panels.dev.matrixtools import pow2mult

BEGIN = ('# BEGIN tangent stiffness product, generated by '
         'theory/shells/tangent_product/write_pyx.py\n')
END = '# END tangent stiffness product\n'

BASIS = re.compile(r'^([fg])A(u|v|w|phix|phiy)((?:xi|eta)*)$')
FUNC = {0: 'f', 1: 'fp', 2: 'fpp'}


class Printer(StrPrinter):
    def _print_Float(self, e):
        return repr(float(e))


def pstr(e):
    reps = {q: Float(q) for q in e.atoms(Rational) if not q.is_Integer}
    return pow2mult(Printer().doprint(e.xreplace(reps)))


def basis_names(exprs):
    names = set()
    for e in exprs:
        names |= {s.name for s in e.free_symbols if BASIS.match(s.name)}
    return names


def ordered(names, fields):
    def key(name):
        fg, field, der = BASIS.match(name).groups()
        return (fg, fields.index(field), len(der))
    return sorted(names, key=key)


def basis_eval(name, index):
    fg, field, der = BASIS.match(name).groups()
    order = der.count('xi') if fg == 'f' else der.count('eta')
    if fg == 'f':
        args = '{0}, xi, x1{1}, x1{1}r, x2{1}, x2{1}r'.format(index, field)
    else:
        args = '{0}, eta, y1{1}, y1{1}r, y2{1}, y2{1}r'.format(index, field)
    return '{0}({1})'.format(FUNC[order], args)


def sum_lines(target, rows, vec, indent):
    r"""``target += sum_k rows[k]*vec[col+k]``, one line"""
    terms = []
    for k, e in enumerate(rows):
        if e == 0:
            continue
        s = pstr(e)
        if e.is_Add:
            s = '(' + s + ')'
        terms.append('{0}*{1}[col+{2}]'.format(s, vec, k))
    if not terms:
        return []
    text = terms[0] + ''.join(' - ' + t[1:] if t.startswith('-') else
                              ' + ' + t for t in terms[1:])
    return ['{0}{1} += {2}'.format(' '*indent, target, text)]


def term_loops(names, fields, body, indent=16):
    r"""Loops over the terms with the basis functions ``names`` read from
    the tables of the integration point"""
    sp = ' '*indent
    out = [sp + 'for j in range(n):']
    for nm in ordered([nm for nm in names if nm.startswith('g')], fields):
        out.append('{0}    {1} = gtab[{2}, j]'.format(sp, nm, TABLE[nm]))
    out.append(sp + '    for i in range(m):')
    for nm in ordered([nm for nm in names if nm.startswith('f')], fields):
        out.append('{0}        {1} = ftab[{2}, i]'.format(sp, nm, TABLE[nm]))
    out.append(sp + '        col = col0 + DOF*(j*m + i)')
    out += body
    return out


TABLE = {}


def pyx_block(model):
    r"""Source of the kernel ``calc_kTv`` of ``model``"""
    tp = th.tangent_product(model)
    op = tp['op']
    fields, NE, DOF = op['fields'], op['NE'], op['DOF']
    cyl = op['geometry'] == 'cylshell'
    tsdt = op['theory'] == 'tsdt'
    ds = {Symbol('ds%d' % i): Symbol('ds[%d]' % i) for i in range(NE)}
    kTv = [collect(e.xreplace(ds), list(ds.values()) + [th.Nxx, th.Nyy,
                   th.Nxy]) for e in tp['kTv']]

    beta_exprs = [e for row in tp['beta'] for e in row]
    eps_exprs = ([e for row in tp['eps'] for e in row]
                 + [e for row in tp['deps'] for e in row])
    all_names = basis_names(beta_exprs + eps_exprs + kTv)
    fnames = ordered([nm for nm in all_names if nm.startswith('f')], fields)
    gnames = ordered([nm for nm in all_names if nm.startswith('g')], fields)
    TABLE.clear()
    TABLE.update({nm: i for i, nm in enumerate(fnames)})
    TABLE.update({nm: i for i, nm in enumerate(gnames)})

    bc_cdef = '\n'.join('    cdef double {0}1{1}, {0}1{1}r, {0}2{1}, {0}2{1}r'
                        .format(d, f) for d in 'xy' for f in fields)
    bc_read = '\n'.join(
        '    {0}1{1} = shell.{0}1{1}; {0}1{1}r = shell.{0}1{1}r; '
        '{0}2{1} = shell.{0}2{1}; {0}2{1}r = shell.{0}2{1}r'.format(d, f)
        for d in 'xy' for f in fields)
    extra_cdef = ''.join([', r' if cyl else '', ', h, c1' if tsdt else ''])
    extra_read = ''
    if cyl:
        extra_read += '    r = shell.r\n'
    if tsdt:
        extra_read += ('    #NOTE the traction-free faces are assumed at z = +-h/2\n'
                       '    h = shell.lam.h\n'
                       '    c1 = 4./(3.*h*h)\n')

    def cdefs(names, per_line=6):
        return '\n'.join('    cdef double ' + ', '.join(names[i:i + per_line])
                         for i in range(0, len(names), per_line))

    out = [BEGIN, '''

def calc_kTv(double [::1] cs, double [::1] vs, object Finput, object shell,
        int size, int col0, int nx, int ny, double Nxx_cte=0.,
        double Nyy_cte=0., double Nxy_cte=0.):
    r"""Product of the tangent stiffness matrix by a vector, without assembly

    Returns `\\boldsymbol{{K}}_T(\\boldsymbol{{c}}) \\boldsymbol{{v}}`, with `\\boldsymbol{{K}}_T` the
    tangent stiffness matrix ``fkC_num(cs, ..., NLgeom=1) + fkG_num(cs, ...)``
    at ``cs``, i.e. the exact Jacobian of :func:`calc_fint`, plus the geometric
    stiffness matrix of the constant membrane stress state ``Nxx_cte``,
    ``Nyy_cte`` and ``Nxy_cte``, multiplied by ``vs``. At each integration
    point, see ``theory/shells/tangent_product``::

        beta = [G] cs,   eps = ([B_L] + [B_NL]/2) cs,   deps = ([B_L] + [B_NL]) vs
        kTv += ([B_L] + [B_NL])^T [F] deps + [G]^T [N] [G] vs

    with ``[N]`` the membrane stresses of ``[F] eps``, plus the constant
    ones. The cost is about that of :func:`calc_fint`.

    Parameters
    ----------
    cs, vs : array-like
        Ritz constants of the configuration and the vector, of size ``size``.
    Finput : array-like
        Constitutive matrix ``({NE}, {NE})``, or one for each integration
        point ``(nx, ny, {NE}, {NE})``.
    shell : :class:`.Shell`
        The shell.
    size, col0 : int
        Size of the vectors and offset of the shell in them.
    nx, ny : int
        Number of integration points.
    Nxx_cte, Nyy_cte, Nxy_cte : float, optional
        Constant membrane stress state.

    Returns
    -------
    kTv : np.ndarray
        The product, of size ``size``.

    """
'''.format(NE=NE)]
    out.append('''    cdef double x1, x2, y1, y2, xinf, xsup, yinf, ysup
    cdef double a, b, intx, inty{extra}
    cdef int m, n
{bc}

    cdef int i, j, col, ptx, pty
    cdef double xi, eta, weight
    cdef double xi1, xi2, eta1, eta2
    cdef double bx, by, dbx, dby, Nxx, Nyy, Nxy
    cdef double e[{NE}]
    cdef double de[{NE}]
    cdef double s[{NE}]
    cdef double ds[{NE}]
{fcdef}
{gcdef}

    cdef double [:, ::1] ftab, gtab
    cdef double [::1] xis, etas, weights_xi, weights_eta, kTv

    # F as 4-D matrix, must be [nx, ny, {NE}, {NE}], when there is one
    # constitutive matrix [{NE}, {NE}] for each of the nx * ny integration points
    cdef double F[{NE2}]
    cdef double [:, :, :, ::1] Fnxny

    cdef int one_F_each_point = 0

    if cs.shape[0] != size or vs.shape[0] != size:
        raise ValueError('cs and vs must have the size %d' % size)
    Finput = np.ascontiguousarray(Finput, dtype=DOUBLE)
    if Finput.shape == (nx, ny, {NE}, {NE}):
        Fnxny = Finput
        one_F_each_point = 1
    elif Finput.shape == ({NE}, {NE}):
        # creating dummy 4-D array that is not used
        Fnxny = np.empty(shape=(0, 0, 0, 0), dtype=DOUBLE)
        # using a constant F for all the integration domain
        for i in range({NE}):
            for j in range({NE}):
                F[i*{NE} + j] = Finput[i, j]
    else:
        raise ValueError('Invalid shape for Finput!')

    if not 'Shell' in shell.__class__.__name__:
        raise ValueError('a Shell object must be given as input')
    a = shell.a
    b = shell.b
    m = shell.m
    n = shell.n
{extra_read}    #NOTE physical limits of the integration domain, resolved and validated
    #      by Shell.integration_limits(); for the full domain the mapping
    #      below gives exactly xi1 = eta1 = -1 and xi2 = eta2 = +1
    x1, x2, y1, y2 = shell.integration_limits()
{bc_read}

    xis, weights_xi = roots_legendre(nx)
    etas, weights_eta = roots_legendre(ny)

    kTv = np.zeros(size, dtype=DOUBLE)
    # basis functions at the integration point
    ftab = np.zeros(({NF}, m), dtype=DOUBLE)
    gtab = np.zeros(({NG}, n), dtype=DOUBLE)

    xinf = 0
    xsup = shell.a
    xi1 = (x1 - xinf)/(xsup - xinf)*2 - 1
    xi2 = (x2 - xinf)/(xsup - xinf)*2 - 1

    yinf = 0
    ysup = shell.b
    eta1 = (y1 - yinf)/(ysup - yinf)*2 - 1
    eta2 = (y2 - yinf)/(ysup - yinf)*2 - 1

    intx = x2 - x1
    inty = y2 - y1

    with nogil:
        for ptx in range(nx):
            for pty in range(ny):
                xi = xis[ptx]
                eta = etas[pty]
                xi = (xi - (-1))/2 * (xi2 - xi1) + xi1
                eta = (eta - (-1))/2 * (eta2 - eta1) + eta1

                # the integrands are per unit area of the natural domain
                weight = weights_xi[ptx]*weights_eta[pty]*intx*inty/4

                if one_F_each_point == 1:
                    for i in range({NE}):
                        for j in range({NE}):
                            F[i*{NE} + j] = Fnxny[ptx, pty, i, j]

'''.format(extra=extra_cdef, bc=bc_cdef, NE=NE, NE2=NE*NE,
           fcdef=cdefs(fnames), gcdef=cdefs(gnames), extra_read=extra_read,
           bc_read=bc_read, NF=len(fnames), NG=len(gnames)))

    lines = ['                for i in range(m):']
    lines += ['                    ftab[{0}, i] = {1}'.format(TABLE[nm],
              basis_eval(nm, 'i')) for nm in fnames]
    lines += ['                for j in range(n):']
    lines += ['                    gtab[{0}, j] = {1}'.format(TABLE[nm],
              basis_eval(nm, 'j')) for nm in gnames]
    out.append('\n'.join(lines) + '\n\n')

    # rotations
    body = []
    for name, rows in zip(('bx', 'by'), tp['beta']):
        body += sum_lines(name, rows, 'cs', 24)
    for name, rows in zip(('dbx', 'dby'), tp['beta']):
        body += sum_lines(name, rows, 'vs', 24)
    out.append('                # rotations of cs and vs\n')
    out.append('                bx = 0.\n                by = 0.\n'
               '                dbx = 0.\n                dby = 0.\n')
    out.append('\n'.join(term_loops(basis_names(beta_exprs), fields, body))
               + '\n\n')

    # strains
    body = []
    for i in range(NE):
        body += sum_lines('e[%d]' % i, tp['eps'][i], 'cs', 24)
    for i in range(NE):
        body += sum_lines('de[%d]' % i, tp['deps'][i], 'vs', 24)
    out.append('''                # strains of cs, eps = ([B_L] + [B_NL]/2) cs, and strain
                # increment, deps = ([B_L] + [B_NL]) vs
                for i in range({NE}):
                    e[i] = 0.
                    de[i] = 0.
'''.format(NE=NE))
    out.append('\n'.join(term_loops(basis_names(eps_exprs), fields, body))
               + '\n\n')

    out.append('''                # stresses
                for i in range({NE}):
                    s[i] = 0.
                    ds[i] = 0.
                    for j in range({NE}):
                        s[i] += F[i*{NE} + j]*e[j]
                        ds[i] += F[i*{NE} + j]*de[j]
                Nxx = s[0] + Nxx_cte
                Nyy = s[1] + Nyy_cte
                Nxy = s[2] + Nxy_cte

'''.format(NE=NE))

    body = ['                        kTv[col+{0}] += weight*({1})'.format(
            k, pstr(e)) for k, e in enumerate(kTv) if e != 0]
    out.append('                # ([B_L] + [B_NL])^T ds + [G]^T [N] [G] vs\n')
    out.append('\n'.join(term_loops(basis_names(kTv), fields, body)) + '\n')
    out.append('''
    return np.asarray(kTv)

''')
    out.append(END)
    return ''.join(out)


def insert_block(model):
    path = os.path.join(REPO, 'panels', 'models', model + '_num.pyx')
    with open(path) as f:
        text = f.read()
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start].rstrip('\n') + '\n\n\n' + text[end:].lstrip('\n')
    text = text.rstrip('\n') + '\n\n\n' + pyx_block(model)
    with open(path, 'w', newline='\n') as f:
        f.write(text)
    print(model, 'tangent stiffness product kernel written')


if __name__ == '__main__':
    for model in sys.argv[1:] or th.MODELS:
        insert_block(model)
