"""Generate the kernels of the model ``cylshell_clpt_gl``

Writes ``panels/models/cylshell_clpt_gl.pyx`` (analytical geometric
stiffness matrix) and ``panels/models/cylshell_clpt_gl_num.pyx``
(numerically integrated matrices, internal force vector, follower-pressure
kernels and product of the tangent stiffness matrix by a vector) from the
derivation of ``cylshell_clpt_gl.py``::

    python write_pyx.py

The linear kernels are those of ``cylshell_clpt_sanders``, whose strains are
the same once the quadratic terms are dropped, and are imported from its
modules: ``fk0``, ``fkM``, ``fkAx``, ``fkAy``, ``fcA``, ``fkM_num``,
``fkAx_num`` and ``fkAy_num``.

The kernels are those of ``plate_clpt_gl/write_pyx.py`` (layout, tables,
assembly of the pairs of terms, ``fkC_num``, ``fkG_num``, ``calc_fint``,
``fkG0``) applied to the eleven generalized derivatives of this model,
``cylshell_clpt_gl.D``, among which the values ``v`` and ``w`` that enter
the strains through the curvature of the reference surface. A private copy
of that generator is loaded and its derivation, tables and model name are
replaced by those of this model; the radius is named ``radius`` in the
kernels, ``r`` being one of their loop indices. The follower-pressure
kernels are those of the Sanders cylinder, whose area vector is the exact
one of the deformed mid-surface (``follower_pressure.MODELS``), and
``calc_kTv`` is generated by ``tangent_product/write_pyx.py`` with the six
local gradients ``cylshell_clpt_gl.BETA``.

"""
import importlib.util
import os
import sys
import textwrap
import types

from sympy import Symbol

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, REPO)

import cylshell_clpt_gl as th


def _load(name, *path):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, *path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


MODEL = 'cylshell_clpt_gl'
#: name of the radius in the kernels
RADIUS = Symbol('radius')

#: rows of the tables of the approximation functions, along x and y
F_ROWS = ['u', 'u_x', 'v', 'v_x', 'w', 'w_x', 'w_xx']
G_ROWS = ['u', 'u_y', 'v', 'v_y', 'w', 'w_y', 'w_yy']

DESC = ('Cylindrical shells using the classical laminated plate theory (CLPT) '
        'with Green-Lagrange membrane strains')

#NOTE a private copy of the generator of plate_clpt_gl, whose module
#     globals are replaced by those of this model
gw = _load('plate_clpt_gl_write_pyx_for_cylshell', '..', 'plate_clpt_gl',
           'write_pyx.py')


def _build():
    return {k: v.xreplace({th.r: RADIUS}) for k, v in th.build().items()}


thc = types.SimpleNamespace(build=_build, D=th.D, D_NAMES=th.D_NAMES,
                            GRAD=th.GRAD, DOF=th.DOF, NE=th.NE, F=th.F,
                            Nxx=th.Nxx, Nyy=th.Nyy, Nxy=th.Nxy, a=th.a,
                            b=th.b, FIELDS=th.FIELDS)
gw.th = thc
gw.MODEL = MODEL
gw.DESC = DESC
gw.DOF, gw.NE, gw.ND, gw.FIELDS = th.DOF, th.NE, len(th.D), th.FIELDS
gw.COMMON_CDEF = gw.COMMON_CDEF + '    cdef double radius\n'
_lim = '    x1, x2, y1, y2 = shell.integration_limits()\n'
assert gw.FINPUT_TEMPLATE.count(_lim) == 1
gw.FINPUT_TEMPLATE = gw.FINPUT_TEMPLATE.replace(
    _lim, _lim + '    radius = shell.r\n')
SPEC = gw.Spec(thc, F_ROWS, G_ROWS)
gw.SPEC = SPEC
gw.M = SPEC.M
gw.PHI_A, gw.PHI_B = SPEC.PHI_A, SPEC.PHI_B
gw.DSET, gw.DOF_OF, gw.D_NAMES = SPEC.DSET, SPEC.DOF_OF, SPEC.D_NAMES
gw.FINPUT = gw.finput(SPEC)
gw.POINT = gw.point(SPEC)

NOTES_STRAINS = r'''Notes
-----
The membrane strains are the Green-Lagrange strains of the mid-surface,
which vanish for any rigid motion, with the changes of curvature of the
Sanders-Koiter kinematics of :mod:`panels.models.cylshell_clpt_sanders`:

.. math::

    \varepsilon_{xx} = u_{,x} + \frac{1}{2} (u_{,x}^2 + v_{,x}^2 +
    w_{,x}^2)

    \varepsilon_{yy} = v_{,y} + \frac{w}{r} + \frac{1}{2} \left(u_{,y}^2 +
    \left(v_{,y} + \frac{w}{r}\right)^2 + \left(w_{,y} -
    \frac{v}{r}\right)^2\right)

    \gamma_{xy} = u_{,y} + v_{,x} + u_{,x} u_{,y} + v_{,x} \left(v_{,y} +
    \frac{w}{r}\right) + w_{,x} \left(w_{,y} - \frac{v}{r}\right)

    \kappa_{xx} = -w_{,xx} \qquad \kappa_{yy} = -w_{,yy} + \frac{v_{,y}}{r}
    \qquad \kappa_{xy} = -2 w_{,xy} + \frac{3}{2} \frac{v_{,x}}{r} -
    \frac{1}{2} \frac{u_{,y}}{r}

with `y` the arc length along the circumference and `w` positive outwards,
the membrane strains of the Flügge-Lur'e-Byrne non-linear theory as
given by Amabili [1]_, Sec. 1.3.6, Eqs. (1.118)-(1.120). They contain the
non-linear terms of :mod:`panels.models.cylshell_clpt_sanders` and also
the quadratic terms of the in-plane gradients, among which those of the
rotation about the normal, `(v_{,x} - u_{,y})/2`, which Sanders [2]_ keeps
and :mod:`panels.models.cylshell_clpt_sanders` omits; under an axial
membrane force `N_{xx}` the geometric stiffness has the term `N_{xx}
v_{,x}^2` besides `N_{xx} w_{,x}^2`, which about halves the column
buckling load of a long tube compared with the Sanders kinematics. The changes of curvature are
linear, measured in the fixed local basis.
'''

REFS = r'''
References
----------
.. [1] Amabili, M., "Nonlinear Vibrations and Stability of Shells and
   Plates", Cambridge University Press, 2008.
   https://doi.org/10.1017/CBO9780511619694
.. [2] Sanders, J. L., "Nonlinear theories for thin shells", Quarterly of
   Applied Mathematics, 21(1), 21-36, 1963.
   https://doi.org/10.1090/qam/147023
'''

GRAD_PLATE = (r'\{u_{,x}, u_{,y}, v_{,x}, v_{,y},' + '\n    '
              + r'w_{,x}, w_{,y}\}^\top` the gradients of the displacements')
GRAD_CYL = (r'\{u_{,x}, u_{,y}, v_{,x}, v_{,y} + w/r,' + '\n    '
            + r'w_{,x}, w_{,y} - v/r\}^\top` the gradients of the displacements'
            + '\n    in the local basis')


def _cyl_text(text):
    n = text.count(GRAD_PLATE)
    assert n >= 1, 'gradient formula not found'
    return text.replace(GRAD_PLATE, GRAD_CYL)


def numerical_module():
    text = gw.numerical_module()
    head, sep, rest = text.partition('\ndef fkC_num(')
    assert sep
    imports = head[head.index('from scipy.sparse import coo_matrix'):]
    old = ('#NOTE the linear kernels, independent of the strains, are those of the von\n'
           '#     Karman plate\n'
           'from .plate_clpt_donnell_num import fkM_num, fkAx_num, fkAy_num\n')
    assert imports.count(old) == 1
    imports = imports.replace(old, (
        '#NOTE the linear kernels, independent of the non-linear strains, are those\n'
        '#     of the Sanders-Koiter cylinder\n'
        'from .cylshell_clpt_sanders_num import fkM_num, fkAx_num, fkAy_num\n'))
    doc = (gw.HEADER + 'r"""\n' + textwrap.fill(DESC, 76) + '''

Numerically integrated kernels of the model ``'cylshell_clpt_gl'``: the
constitutive stiffness :func:`fkC_num`, the geometric stiffness
:func:`fkG_num`, the internal force vector :func:`calc_fint`, the product
of the tangent stiffness matrix by a vector :func:`calc_kTv`, and the force
vector and load stiffness matrix of a follower pressure,
:func:`calc_fext_follower` and :func:`fkCfollower_num`. The mass and
aerodynamic matrices, ``fkM_num``, ``fkAx_num`` and ``fkAy_num``, are those
of :mod:`panels.models.cylshell_clpt_sanders_num`. The constitutive matrix
``Finput`` is the ``6 x 6`` matrix ``ABD`` of the CLPT.

The degrees of freedom of each term of the approximation are
``u, v, w``; the degree of freedom ``k`` of the term ``(i, j)``, ``0 <=
i < m``, ``0 <= j < n``, is at the row ``row0 + 3*(j*m + i) + k``
of the matrices.

''' + NOTES_STRAINS + '''
The numerical integration over the domain of
:meth:`.Shell.integration_limits` admits a constitutive matrix and moments
of the density varying over the domain, a partial domain and the
non-linear terms of the Ritz constants.
''' + REFS + '''
"""
''')
    return _cyl_text(doc + imports + sep + rest)


def analytical_module():
    text = gw.analytical_module()
    head, sep, rest = text.partition('\ndef fkG0(')
    assert sep
    imports = head[head.index('from scipy.sparse import coo_matrix'):]
    old = ('#NOTE the linear kernels, independent of the strains, are those of the von\n'
           '#     Karman plate\n'
           'from .plate_clpt_donnell import fk0, fkM, fkAx, fkAy, fcA\n')
    assert imports.count(old) == 1
    imports = imports.replace(old, (
        '#NOTE the linear kernels, independent of the non-linear strains, are those\n'
        '#     of the Sanders-Koiter cylinder\n'
        'from .cylshell_clpt_sanders import fk0, fkM, fkAx, fkAy, fcA\n'))
    doc = (gw.HEADER + 'r"""\n' + textwrap.fill(DESC, 76) + '''

Analytical kernels of the model ``'cylshell_clpt_gl'``, integrated over
the whole domain. The linear constitutive stiffness ``fk0``, the mass
``fkM`` and the aerodynamic ``fkAx``, ``fkAy`` and ``fcA`` matrices are
those of :mod:`panels.models.cylshell_clpt_sanders`. The geometric
stiffness matrix :func:`fkG0` of the constant membrane stress state ``Nxx,
Nyy, Nxy`` has one block per local gradient of ``u``, ``v`` and ``w``.

''' + NOTES_STRAINS + '''
The integrals over the whole domain are evaluated in closed form with the
integrals of Bardell's functions and their derivatives along `\\xi = 2x/a -
1` and `\\eta = 2y/b - 1`, which requires the constitutive matrix and the
moments of the density to be constant over the domain.
''' + REFS + '''
"""
''')
    for old, new in (('    cdef double a, b\n', '    cdef double a, b, radius\n'),
                     ('    b = shell.b\n', '    b = shell.b\n    radius = shell.r\n')):
        assert rest.count(old) == 1, old
        rest = rest.replace(old, new)
    return _cyl_text(doc + imports + sep + rest)


def generate():
    path = os.path.join(REPO, 'panels', 'models', MODEL + '.pyx')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(analytical_module())
    print(MODEL, 'analytical written')
    path = os.path.join(REPO, 'panels', 'models', MODEL + '_num.pyx')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(numerical_module() + '\n\n' + gw.follower_block(MODEL)
                + '\n\n' + gw.tangent_block(MODEL))
    print(MODEL, 'numerical written')


if __name__ == '__main__':
    generate()
