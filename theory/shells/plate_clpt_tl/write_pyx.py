"""Generate the kernels of the model ``plate_clpt_tl``

Writes ``panels/models/plate_clpt_tl_num.pyx`` (numerically integrated
matrices, internal force vector, follower-pressure kernels and product of the
tangent stiffness matrix by a vector) from the derivation of
``plate_clpt_tl.py``::

    python write_pyx.py

The analytical kernels are those of :mod:`panels.models.plate_clpt_gl`: the
linear strains are those of ``plate_clpt_donnell`` (``fk0``, ``fkM``,
``fkAx``, ``fkAy``, ``fcA``), and the geometric stiffness of a constant
membrane stress state (``fkG0``) is that of the Green-Lagrange membrane
strains, the curvatures only adding terms of the moments. The mass and
aerodynamic matrices of the numerical module, ``fkM_num``, ``fkAx_num`` and
``fkAy_num``, are imported from :mod:`panels.models.plate_clpt_donnell_num`.

The kernels use the helpers of ``plate_clpt_gl/write_pyx.py`` (layout,
tables, assembly of the pairs of terms, ``calc_fint``) with the fifteen
generalized derivatives of this model, among which the second derivatives of
``u`` and ``v``: the tables of the approximation functions have nine rows
along each direction instead of seven. ``fkC_num`` and ``fkG_num`` differ
from those of ``plate_clpt_gl`` by ``[B]``, quadratic in the derivatives, and
by the Hessian of the curvatures, linear in them; ``calc_kTv`` evaluates
``[B]^T [ABD] [B] v + [H(sigma, d)] v`` at each point, since the strains are
no longer of the form assumed by ``theory/shells/tangent_product``.

"""
import importlib.util
import os
import sys
import textwrap

import sympy
from sympy import Matrix, Symbol, expand

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, REPO)

import plate_clpt_tl as th


def _load(name, *path):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, *path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


#NOTE the helpers of the kernels of plate_clpt_gl
gw = _load('plate_clpt_gl_write_pyx', '..', 'plate_clpt_gl', 'write_pyx.py')
pstr = gw.pstr
matrix_lines = gw.matrix_lines

MODEL = 'plate_clpt_tl'
DOF = th.DOF
NE = th.NE
ND = len(th.D)

#: rows of the tables of the approximation functions, along x and y
F_ROWS = ['u', 'u_x', 'u_xx', 'v', 'v_x', 'v_xx', 'w', 'w_x', 'w_xx']
G_ROWS = ['u', 'u_y', 'u_yy', 'v', 'v_y', 'v_yy', 'w', 'w_y', 'w_yy']

SP = gw.Spec(th, F_ROWS, G_ROWS)
D_NAMES = SP.D_NAMES
FINPUT = gw.finput(SP)
POINT = gw.point(SP)
COMMON = gw.COMMON_CDEF

SG = [Symbol('sg[%d]' % r) for r in range(NE)]
SGL = [Symbol('sgL[%d]' % r) for r in range(NE)]

DESC = ('Flat plates using the classical laminated plate theory (CLPT), '
        'total Lagrangian: Green-Lagrange membrane strains and changes of '
        'curvature measured with the deformed normal')


def cdefs(names, per=8):
    return '\n'.join('    cdef double ' + ', '.join(names[i:i + per])
                     for i in range(0, len(names), per))


def zero_lines(names, indent=16):
    return '\n'.join('{0}{1} = 0.'.format(' '*indent, nm) for nm in names)


def stresses(e, sg, indent=16):
    sp = ' '*indent
    return '\n'.join([sp + 'for r in range(6):',
                      sp + '    {0}[r] = 0.'.format(sg),
                      sp + '    for s in range(6):',
                      sp + '        {0}[r] += F[r*6 + s]*{1}[s]'.format(sg, e)])


def numerical_module():
    m = SP.M
    B, eps, eps_L, H, H0 = m['B'], m['eps'], m['eps_L'], m['H'], m['H0']
    alld = list(range(ND))
    full = [[True]*ND for _ in range(ND)]
    blocks_all = [(d, e) for d in range(DOF) for e in range(DOF)]

    out = [gw.HEADER + 'r"""\n' + textwrap.fill(DESC, 76) + '''

Numerically integrated matrices and internal force vector of the model
``'plate_clpt_tl'``, generated by ``theory/shells/plate_clpt_tl/write_pyx.py``
from the derivation of ``theory/shells/plate_clpt_tl/plate_clpt_tl.py``.
The degrees of freedom of each term of the approximation are ``u, v, w``,
and the constitutive matrix ``Finput`` is the ``6 x 6`` matrix ``ABD`` of the
CLPT. The membrane strains are the Green-Lagrange strains of
``'plate_clpt_gl'``::

    exx = u,x + (u,x^2 + v,x^2 + w,x^2)/2
    eyy = v,y + (u,y^2 + v,y^2 + w,y^2)/2
    gxy = u,y + v,x + u,x u,y + v,x v,y + w,x w,y

and the changes of curvature are measured with the area vector of the
deformed mid-surface, ``a = X,x x X,y``, ``X = (x, y, 0) + (u, v, w)``::

    kxx = -a . (u,xx, v,xx, w,xx)
    kyy = -a . (u,yy, v,yy, w,yy)
    kxy = -2 a . (u,xy, v,xy, w,xy)

which are cubic in the displacements. The integrands are polynomials of
degree ``6p - 2`` along each direction for approximation functions of degree
``p``, integrated exactly by ``3p`` Gauss-Legendre points, the default of
:class:`.Shell` for this model. The mass and aerodynamic matrices,
``fkM_num``, ``fkAx_num`` and ``fkAy_num``, are those of
:mod:`panels.models.plate_clpt_donnell_num`.

"""
from scipy.sparse import coo_matrix
import numpy as np
from scipy.special import roots_legendre

from panels import INT, DOUBLE
#NOTE the linear kernels, independent of the strains, are those of the von
#     Karman plate
from .plate_clpt_donnell_num import fkM_num, fkAx_num, fkAy_num


cdef extern from 'bardell_functions.hpp':
    double f(int i, double xi, double xi1t, double xi1r, double xi2t, double xi2r) nogil
    double fp(int i, double xi, double xi1t, double xi1r, double xi2t, double xi2r) nogil
    double fpp(int i, double xi, double xi1t, double xi1r, double xi2t, double xi2r) nogil

cdef int DOF = 3
''']

    # ------------------------------------------------------------- fkC_num
    Hd = (H.xreplace(dict(zip(th.STRESSES, SG)))
          - H0.xreplace(dict(zip(th.STRESSES, SGL)))).applyfunc(expand)
    out.append('''

def fkC_num(double [::1] cs, object Finput, object shell,
        int size, int row0, int col0, int nx, int ny, int NLgeom=0):
    r"""Constitutive stiffness matrix, ``KC0 + KCNL + KGNL``

    With ``NLgeom=1`` the matrix at the state ``cs`` is
    ``int [Phi]^T ([B]^T [ABD] [B] + [H(sigma, d)] - [H0(sigma_L)]) [Phi]
    dA``, with ``[B] = d eps/d d``, ``[H(sigma, d)] = sum_r sigma_r d^2
    eps_r/d d^2`` at the stresses ``sigma = [ABD] eps``, and ``[H0(sigma_L)]``
    its value at ``d = 0`` with the stresses of the linear strains, the part
    assembled by :func:`.fkG_num`, such that ``KT = fkC_num + fkG_num`` is the
    exact Jacobian of :func:`.calc_fint`. With ``NLgeom=0`` it is the linear
    constitutive stiffness matrix ``KC0``.

    """
{COMMON}
{dcdef}
    cdef double e[6]
    cdef double eL[6]
    cdef double sg[6]
    cdef double sgL[6]
{basis}
    cdef double Bm[{NB}]
    cdef double FB[{NB}]
    cdef double K[{NK}]
    cdef double TA[{NT}]
    cdef double pA[{ND}]
    cdef double pB[{ND}]

    cdef long [::1] kCr, kCc
    cdef double [::1] kCv

{FINPUT}

    fdim = 9*m*m*n*n
    kCr = np.zeros((fdim,), dtype=INT)
    kCc = np.zeros((fdim,), dtype=INT)
    kCv = np.zeros((fdim,), dtype=DOUBLE)

{POINT}
                # generalized derivatives at the point, zero when NLgeom == 0
{dzero}
                if NLgeom == 1:
{dloop}

                # [B] = d eps/d d at the point
                for p in range({NB}):
                    Bm[p] = 0.
{Blines}

                # K = [B]^T [ABD] [B]
                for r in range(6):
                    for q in range({ND}):
                        FB[r*{ND} + q] = 0.
                        for s in range(6):
                            FB[r*{ND} + q] += F[r*6 + s]*Bm[s*{ND} + q]
                for p in range({ND}):
                    for q in range({ND}):
                        K[p*{ND} + q] = 0.
                        for r in range(6):
                            K[p*{ND} + q] += Bm[r*{ND} + p]*FB[r*{ND} + q]

                # stresses of the strains and of the linear strains
{elines}
{eLlines}
{sg}
{sgL}
                # K += [H(sigma, d)] - [H0(sigma_L)], the second term being
                # assembled by fkG_num, which is homogeneous of degree one
                # in cs as linear buckling requires
{Hlines}

{loops}

    kC = coo_matrix((kCv, (kCr, kCc)), shape=(size, size))

    return kC
'''.format(COMMON=COMMON, dcdef=cdefs(list(D_NAMES)), basis=gw.basis_cdef('AB', SP),
           NB=NE*ND, NK=ND*ND, NT=DOF*ND, ND=ND, FINPUT=FINPUT, POINT=POINT,
           dzero=zero_lines(D_NAMES),
           dloop='\n'.join(gw.gradient_loop(20, alld, SP)),
           Blines='\n'.join(matrix_lines('Bm', B, 16)),
           elines='\n'.join('                e[{0}] = {1}'.format(k, pstr(eps[k])) for k in range(NE)),
           eLlines='\n'.join('                eL[{0}] = {1}'.format(k, pstr(eps_L[k])) for k in range(NE)),
           sg=stresses('e', 'sg'), sgL=stresses('eL', 'sgL'),
           Hlines='\n'.join(matrix_lines('K', Hd, 16, op='+=')),
           loops=gw.assembly('kC', full, blocks_all, sp=SP)))

    # ------------------------------------------------------------- fkG_num
    H0s = H0.xreplace(dict(zip(th.STRESSES, SG))).applyfunc(expand)
    H0pat = [[H0[p, q] != 0 for q in range(ND)] for p in range(ND)]
    blocks = [(d, e) for d in range(DOF) for e in range(DOF)
              if any(H0pat[p][q] for p in SP.DSET[d] for q in SP.DSET[e])]
    lin = [p for p in range(ND) if th.D[p] in set().union(*[x.free_symbols for x in eps_L])]
    out.append('''

def fkG_num(double [::1] cs, object Finput, object shell,
            int size, int row0, int col0, int nx, int ny,
            double Nxx0=0, double Nyy0=0, double Nxy0=0):
    r"""Geometric stiffness matrix of the linear stress state

    ``int [Phi]^T [H0(sigma)] [Phi] dA``, with ``sigma = (Nxx0, Nyy0, Nxy0,
    0, 0, 0) + sigma_L``, ``sigma_L`` the stresses of the *linear* strains at
    ``cs``, and ``[H0]`` the second derivative of the strains at ``d = 0``:
    one block ``[[Nxx, Nxy], [Nxy, Nyy]]`` for each of the gradients of
    ``u``, ``v`` and ``w``, as in ``plate_clpt_gl``, and the coupling of the
    gradients of ``u`` and ``v`` with the second derivatives of ``w``, and of
    the gradients of ``w`` with the second derivatives of ``u`` and ``v``,
    by the moments ``Mxx, Myy, Mxy``. The result is homogeneous of degree one
    in ``cs``, which is what the linear buckling eigenvalue problem requires.
    The rest of the tangent stiffness enters through :func:`.fkC_num`, such
    that

        KT = KC0 + KCNL + KGNL   (fkC_num)
             + KG(Nbar + sigma_L)  (fkG_num)

    is the exact Jacobian of :func:`.calc_fint`.

    """
{COMMON}
{dcdef}
    cdef double e[6]
    cdef double sg[6]
{basis}
    cdef double K[{NK}]
    cdef double TA[{NT}]
    cdef double pA[{ND}]
    cdef double pB[{ND}]

    cdef long [::1] kGr, kGc
    cdef double [::1] kGv

{FINPUT}

    fdim = {NBLK}*m*m*n*n
    kGr = np.zeros((fdim,), dtype=INT)
    kGc = np.zeros((fdim,), dtype=INT)
    kGv = np.zeros((fdim,), dtype=DOUBLE)

{POINT}
                # derivatives of the linear strains at the point
{dzero}
{dloop}

                # linear strains and stresses
{elines}
{sg}
                sg[0] += Nxx0
                sg[1] += Nyy0
                sg[2] += Nxy0

                # K = [H0(sigma)]
{Hlines}

{loops}

    kG = coo_matrix((kGv, (kGr, kGc)), shape=(size, size))

    return kG
'''.format(COMMON=COMMON, dcdef=cdefs([D_NAMES[p] for p in lin]),
           basis=gw.basis_cdef('AB', SP), NK=ND*ND, NT=DOF*ND, ND=ND,
           FINPUT=FINPUT, POINT=POINT, NBLK=len(blocks),
           dzero=zero_lines([D_NAMES[p] for p in lin]),
           dloop='\n'.join(gw.gradient_loop(16, lin, SP)),
           elines='\n'.join('                e[{0}] = {1}'.format(k, pstr(eps_L[k])) for k in range(NE)),
           sg=stresses('e', 'sg'),
           Hlines='\n'.join(matrix_lines('K', H0s, 16)),
           loops=gw.assembly('kG', H0pat, blocks, sp=SP)))

    # ------------------------------------------------------------- calc_fint
    out.append(gw.calc_fint_src(SP))

    # ------------------------------------------------------------- calc_kTv
    out.append(calc_kTv_src())
    text = ''.join(out)
    #NOTE c, p, q, r, s, k, l and parts of the tables are not used in every
    #     kernel, which is harmless
    return text


def calc_kTv_src():
    r"""``calc_kTv``: ``K_T v = int [Phi]^T ([B]^T [ABD] [B] [Phi] v + [H(sigma
    + Nbar, d)] [Phi] v) dA`` at each point"""
    m = SP.M
    B, eps, H = m['B'], m['eps'], m['H']
    dv = Matrix([Symbol('d' + nm) for nm in D_NAMES])
    DSG = Matrix([Symbol('dsg[%d]' % r) for r in range(NE)])
    de = (B*dv).applyfunc(expand)
    S = (B.T*DSG + H.xreplace(dict(zip(th.STRESSES, SG)))*dv).applyfunc(expand)
    kTv_lines = []
    for d in range(DOF):
        terms = ['pA[{0}]*S[{0}]'.format(p) for p in SP.DSET[d]]
        kTv_lines.append('                        kTv[col+{0}] += weight*({1})'.format(d, ' + '.join(terms)))
    alld = list(range(ND))
    return '''

def calc_kTv(double [::1] cs, double [::1] vs, object Finput, object shell,
        int size, int col0, int nx, int ny, double Nxx_cte=0.,
        double Nyy_cte=0., double Nxy_cte=0.):
    r"""Product of the tangent stiffness matrix by a vector, without assembly

    Returns `\\boldsymbol{{K}}_T(\\boldsymbol{{c}}) \\boldsymbol{{v}}`, with `\\boldsymbol{{K}}_T` the
    tangent stiffness matrix ``fkC_num(cs, ..., NLgeom=1) + fkG_num(cs, ...)``
    at ``cs``, i.e. the exact Jacobian of :func:`calc_fint`, plus the geometric
    stiffness matrix of the constant membrane stress state ``Nxx_cte``,
    ``Nyy_cte`` and ``Nxy_cte``, multiplied by ``vs``. At each integration
    point, with ``d = [Phi] cs`` and ``dv = [Phi] vs``::

        kTv += [Phi]^T ([B(d)]^T [ABD] [B(d)] dv + [H(sigma + Nbar, d)] dv)

    with ``sigma = [ABD] eps(d)``. The cost is about that of
    :func:`calc_fint`.

    Parameters
    ----------
    cs, vs : array-like
        Ritz constants of the configuration and the vector, of size ``size``.
    Finput : array-like
        Constitutive matrix ``(6, 6)``, or one for each integration point
        ``(nx, ny, 6, 6)``.
    shell : :class:`.Shell`
        The shell.
    size, col0 : int
        Size of the vectors and offset of the shell in them.
    nx, ny : int
        Number of integration points.
    Nxx_cte, Nyy_cte, Nxy_cte : float, optional
        Constant membrane stress state.

    Returns
    -------
    kTv : np.ndarray
        The product, of size ``size``.

    """
{COMMON}
{dcdef}
{ddcdef}
    cdef double e[6]
    cdef double de[6]
    cdef double sg[6]
    cdef double dsg[6]
    cdef double S[{ND}]
    cdef double pA[{ND}]
{basis}

    cdef double [::1] kTv

    if cs.shape[0] != size or vs.shape[0] != size:
        raise ValueError('cs and vs must have the size %d' % size)

{FINPUT}

    kTv = np.zeros(size, dtype=DOUBLE)

{POINT}
                # generalized derivatives of cs and vs at the point
{dzero}
{ddzero}
{dloop}

                # strains, strain increments, stresses
{elines}
{delines}
{sg}
{dsg}
                sg[0] += Nxx_cte
                sg[1] += Nyy_cte
                sg[2] += Nxy_cte

                # S = [B]^T dsigma + [H(sigma, d)] dv
{Slines}

                for j in range(n):
{gA}
                    for i in range(m):
{fA}
                        col = col0 + DOF*(j*m + i)
{pA}
{kTv}

    return np.asarray(kTv)
'''.format(COMMON=COMMON, dcdef=cdefs(list(D_NAMES)),
           ddcdef=cdefs(['d' + nm for nm in D_NAMES]), ND=ND,
           basis=gw.basis_cdef('A', SP), FINPUT=FINPUT, POINT=POINT,
           dzero=zero_lines(D_NAMES), ddzero=zero_lines(['d' + nm for nm in D_NAMES]),
           dloop='\n'.join(gw.gradient_loop(16, alld, SP, extra=(('vs', 'd'),))),
           elines='\n'.join('                e[{0}] = {1}'.format(k, pstr(eps[k])) for k in range(NE)),
           delines='\n'.join('                de[{0}] = {1}'.format(k, pstr(de[k])) for k in range(NE)),
           sg=stresses('e', 'sg'), dsg=stresses('de', 'dsg'),
           Slines='\n'.join('                S[{0}] = {1}'.format(p, pstr(S[p])) for p in range(ND)),
           gA='\n'.join(gw.basis_read('A', 'g', 20, SP)),
           fA='\n'.join(gw.basis_read('A', 'f', 24, SP)),
           pA='\n'.join(gw.phi_lines('A', 24, SP)), kTv='\n'.join(kTv_lines))


def generate():
    path = os.path.join(REPO, 'panels', 'models', MODEL + '_num.pyx')
    with open(path, 'w', newline='\n') as f:
        f.write(numerical_module() + '\n\n' + gw.follower_block(MODEL))
    print(MODEL, 'numerical written')


if __name__ == '__main__':
    generate()
