r"""Generator of ``panels/core/src/bardell_functions.cpp``

Writes the C++ functions ``vec_f``, ``vec_fp``, ``vec_fpp``, ``f``, ``fp`` and
``fpp`` that evaluate the 30 terms of Bardell's hierarchical functions and
their first and second derivatives at a natural coordinate `\xi`, declared in
``panels/core/include/bardell_functions.hpp``.

Each polynomial is evaluated by Horner's rule, without ``pow()``: the terms
``0`` to ``3`` (cubic Hermite polynomials, mixed parity) in `\xi`, the terms
``4`` to ``29`` and their derivatives, which are either even or odd in `\xi`,
in `\xi^2`, an odd polynomial as `\xi\,q(\xi^2)`. The coefficients are the
exact rationals of the definition, written as the correctly rounded doubles
(shortest round-trip decimal strings).

Run from any directory::

    python theory/func/bardell/bardell_functions_C.py

Notes
-----
Horner's rule evaluates `p(t) = \sum_{k=0}^{n} a_k t^k` as
`a_0 + t(a_1 + t(a_2 + \dots + t a_n))`, with `n` multiplications and `n`
additions, and its computed value is the exact value of a polynomial whose
coefficients are perturbed by at most `\gamma_{2n} |a_k|`, with
`\gamma_{2n} = 2nu/(1 - 2nu)` and `u` the unit round-off, such that
`|p(t) - \hat{p}(t)| \le \gamma_{2n} \sum_k |a_k| |t|^k` [1]_. It needs no
``pow()`` and is backward stable; the error bound has the same form as that
of the sum of the monomials, and the cancellation between the large
coefficients of alternating sign of the terms of high degree remains.

References
----------
.. [1] Higham, N. J., "Accuracy and Stability of Numerical Algorithms", 2nd
   ed., SIAM, Philadelphia, 2002, Chapter 5, Polynomials, pp. 93-104.
   https://doi.org/10.1137/1.9780898718027.ch5

"""
import os
from fractions import Fraction

from sympy import Poly, Rational, diff, factorial, factorial2, symbols

NUM = 30

xi = symbols('xi')


def bardell_polynomials(nmax=NUM):
    r"""Exact Bardell polynomials

    Parameters
    ----------
    nmax : int, optional
        Number of terms.

    Returns
    -------
    u : list of SymPy expressions
        The terms ``0`` to ``nmax - 1`` with exact rational coefficients,
        the first four without their boundary-condition flags.

    """
    u = [Rational(1, 2) - Rational(3, 4)*xi + Rational(1, 4)*xi**3,
         Rational(1, 8) - Rational(1, 8)*xi - Rational(1, 8)*xi**2 + Rational(1, 8)*xi**3,
         Rational(1, 2) + Rational(3, 4)*xi - Rational(1, 4)*xi**3,
         -Rational(1, 8) - Rational(1, 8)*xi + Rational(1, 8)*xi**2 + Rational(1, 8)*xi**3]
    for r in range(5, nmax + 1):
        terms = []
        for n in range(0, r//2 + 1):
            p = r - 2*n - 1
            if p < 0:
                continue
            den = 2**n*factorial(n)*factorial(p)
            terms.append((-1)**n*factorial2(2*r - 2*n - 7)/den*xi**p)
        u.append(sum(terms))
    return u


def exact_coefficients(expr):
    """Coefficients ``a_0, a_1, ...`` of a polynomial in ``xi`` as Fractions"""
    coeffs = Poly(expr, xi).all_coeffs()[::-1]
    return [Fraction(int(c.p), int(c.q)) for c in coeffs]


def _literal(c):
    s = repr(float(c))
    if 'e' not in s and '.' not in s:
        s += '.'
    return s


def _horner(coeffs, var):
    # coeffs: a_0 ... a_n (Fractions), returns a C expression
    coeffs = list(coeffs)
    while len(coeffs) > 1 and coeffs[-1] == 0:
        coeffs.pop()
    an = coeffs[-1]
    expr = _literal(an) if an >= 0 else '(%s)' % _literal(an)
    for a in reversed(coeffs[:-1]):
        inner = expr if (' ' not in expr and '*' not in expr) else '(%s)' % expr
        if a == 0:
            expr = '%s*%s' % (var, inner)
        else:
            expr = '%s + %s*%s' % (_literal(a), var, inner)
    return expr


def horner_ccode(expr):
    r"""C expression of a polynomial in ``xi`` by Horner's rule

    A polynomial that is even or odd in ``xi`` is evaluated in ``xi2``, the
    variable that the generated functions define as ``xi*xi``.

    """
    a = exact_coefficients(expr)
    if all(c == 0 for c in a):
        return '0.'
    odd = all(c == 0 for c in a[0::2])
    even = all(c == 0 for c in a[1::2])
    if even:
        return _horner(a[0::2], 'xi2')
    if odd:
        return 'xi*(%s)' % _horner(a[1::2], 'xi2')
    return _horner(a, 'xi')


def write_cpp(path):
    u = bardell_polynomials()
    consts = {0: 'xi1t', 1: 'xi1r', 2: 'xi2t', 3: 'xi2r'}
    funcs = [('vec_f', 'f', 'f', u),
             ('vec_fp', 'fp', 'fp', [diff(ui, xi) for ui in u]),
             ('vec_fpp', 'fpp', 'fpp', [diff(ui, xi, xi) for ui in u])]

    def body(i, polys):
        code = horner_ccode(polys[i])
        const = consts.get(i)
        if const is None:
            return code
        return '%s*(%s)' % (const, code)

    with open(path, 'w', newline='\n') as f:
        f.write("// Bardell's hierarchical functions\n\n")
        f.write('// Number of terms: {0}\n\n'.format(len(u)))
        f.write('// Generated by theory/func/bardell/bardell_functions_C.py: each\n')
        f.write('// polynomial evaluated by Horner\'s rule in xi, or in xi2 = xi*xi\n')
        f.write('// when it is even or odd in xi; do not edit by hand\n\n')
        f.write('#include <stdlib.h>\n')
        f.write('#include <math.h>\n\n')
        f.write('#if defined(_WIN32) || defined(__WIN32__)\n')
        f.write('  #define EXPORTIT __declspec(dllexport)\n')
        f.write('#else\n')
        f.write('  #define EXPORTIT\n')
        f.write('#endif\n\n')
        comments = {
            'vec_f': '// Vec containing all the SFs (element is one term)\n',
            'vec_fp': '// Vec containing the first derivatives of all the SFs\n',
            'vec_fpp': '// Vec containing the second derivatives of all the SFs\n',
            'f': '// Generates a single shape function, based on the bardell function number\n',
            'fp': '// p = prime\n',
            'fpp': '// pp = second derivative\n',
            }
        for vname, _, out, polys in funcs:
            f.write(comments[vname])
            f.write('EXPORTIT void %s(double *%s, double xi,\n' % (vname, out)
                    + '           double xi1t, double xi1r, double xi2t, double xi2r) {\n')
            f.write('    const double xi2 = xi*xi;\n')
            for i in range(len(u)):
                f.write('    %s[%d] = %s;\n' % (out, i, body(i, polys)))
            f.write('}\n\n\n')
        for k, (_, sname, _, polys) in enumerate(funcs):
            f.write(comments[sname])
            f.write('EXPORTIT double %s(int i, double xi,\n' % sname
                    + '           double xi1t, double xi1r, double xi2t, double xi2r) {\n')
            f.write('    const double xi2 = xi*xi;\n')
            f.write('    switch(i) {\n')
            for i in range(len(u)):
                f.write('    case %d:\n' % i)
                f.write('        return %s;\n' % body(i, polys))
            f.write('    default:\n')
            f.write('        return 0.;\n')
            f.write('    }\n')
            f.write('}\n')
            if k < len(funcs) - 1:
                f.write('\n\n')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    write_cpp(os.path.join(here, '..', '..', '..', 'panels', 'core', 'src',
                           'bardell_functions.cpp'))
